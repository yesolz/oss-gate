"""Build the self-contained CLI plugin from the canonical OSS Gate source."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {".venv", "__pycache__", ".ruff_cache", ".pytest_cache"}
DESCRIPTION = "Open-source adoption reviews through a local CLI. Korean and English reports with preserved evidence; no MCP servers registered."
CLI_TRANSPORT = """# CLI execution

This installation is `oss-gate-cli`. Execute the review through the bundled CLI;
do not register or call OSS Gate MCP tools. Resolve `<plugin-root>` from this
skill's location (`../..`). Read `execution.md` for command arguments and policy.

Workflow operation mapping:

| Operation | CLI command |
|---|---|
| `get_project(repo)` | `project <repo> --out <new-project.json>` |
| `audit_manifest(text, type)` | `audit <sanitized-file> --type <type> --out <new-audit.json>` |
| `collect_review(...)` | `collect <system> <name> --version <version> --repo <repo> --output-root <directory>` |
| DeepWiki explanation | `explain <owner/repo> --topic <topic> --out <new-topic.json>` |
| HTML output | `render <review-directory> --language <ko|en|both>` |

Prefix every command with `uv run --frozen --project "<plugin-root>" python
"<plugin-root>/cli.py"`. Place optional `--policy` before the subcommand.
Use new output paths in an existing directory. Read the full saved JSON, not
only the short stdout result. `project` candidates require identity checks;
`audit` consumes only a locally inspected, sanitized manifest. A policy block
or an unsupported repository host is a coverage gap, never a reason to switch
tools. DeepWiki remains an optional external service accessed by fixed topics.

Write the narrative from the collected evidence before rendering. The same
workflow, language rules and verification requirements apply in CLI mode.
"""


def expected_files(root=ROOT):
    source = root / "plugins/oss-gate"
    for directory in ("core", "skills", "policies"):
        if any(p.is_symlink() for p in (source / directory).rglob("*")) or (source / directory).is_symlink():
            raise ValueError("symlinks are not supported in canonical CLI content")
    paths = [source / p for p in ("LICENSE", "pyproject.toml", "uv.lock", "cli.py", "render.py", "portfolio.py")]
    for directory in ("core", "skills", "policies"):
        paths.extend(p for p in (source / directory).rglob("*") if p.is_file() and not set(p.parts) & EXCLUDED)
    result = {}
    for p in paths:
        if p.is_symlink():
            raise ValueError(f"symlink in canonical plugin: {p.relative_to(source)}")
        result[p.relative_to(source).as_posix()] = p.read_bytes()
    for name in ("plugin.json", ".claude-plugin/plugin.json"):
        manifest = json.loads((source / name).read_text(encoding="utf-8"))
        manifest.update(name="oss-gate-cli", description=DESCRIPTION)
        result[name] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    result["skills/oss-review/references/transport.md"] = CLI_TRANSPORT.encode()
    result["README.md"] = (
        "# OSS Gate CLI plugin\n\n"
        "Generated by `scripts/build_cli_plugin.py` from `plugins/oss-gate`; edit the canonical source.\n\n"
        "This package registers no MCP servers. Use its oss-review skill to collect evidence, write a narrative "
        "and render Korean or English reports through the local CLI. Run `cli.py --help` for commands.\n\n"
        "Requires uv and Python 3.10+. DeepWiki is still external when called. Runtime dependencies include "
        "its MCP client library; no OSS Gate MCP server is started or registered by this package.\n"
    ).encode()
    return result


def build(check=False, root=ROOT):
    target = root / "plugins/oss-gate-cli"
    expected = expected_files(root)
    actual = {
        p.relative_to(target).as_posix(): p
        for p in target.rglob("*")
        if p.is_file() and not set(p.relative_to(target).parts) & EXCLUDED
    }
    if any(p.is_symlink() for p in target.rglob("*")) or target.is_symlink():
        raise ValueError("symlinks are not supported in the generated CLI plugin")
    different = [name for name, data in expected.items() if name not in actual or actual[name].read_bytes() != data]
    extra = set(actual) - set(expected)
    if check:
        if different or extra:
            raise ValueError(
                "CLI plugin is stale; run scripts/build_cli_plugin.py: " + ", ".join(sorted(set(different) | extra))
            )
    else:
        for name in extra:
            actual[name].unlink()
        for name in different:
            path = target / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[name])
    print(f"PASS: CLI plugin {'matches' if check else 'built from'} canonical source ({len(expected)} files)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed CLI files differ; do not modify them")
    build(parser.parse_args().check)
